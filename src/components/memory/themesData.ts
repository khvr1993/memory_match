export function preloadThemeImages(theme: MemoryTheme): void {
  if (typeof Image === 'undefined') return;
  for (const symbol of theme.symbols) {
    if (!symbol.image) continue;
    const image = new Image();
    image.src = symbol.image;
  }
}
